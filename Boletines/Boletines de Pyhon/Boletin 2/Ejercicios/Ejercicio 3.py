# 3. Escribir un programa en python que nos pida las notas de los dos trimestres y nos
# muestre la media aritmética resultante

nota1 = int(input("Dime tu nota del primer trimestre: "))
nota2 = int(input("Dime tu nota del segundo trimestre: "))

nota_aritmetica = (nota1 + nota2) / 2

print("La media aritmetica del curso es: ", nota_aritmetica)